/**
 * Product image checklist + AI-image prompt sheet.
 *
 *   node scripts/image-manifest.mjs          → prints which product/type photos are still missing
 *   node scripts/image-manifest.mjs --write  → also writes docs/product-images.md (file names + prompts)
 *
 * Photos live in public/images/products/<product-slug>/ and are picked up by file name
 * (see src/lib/productImages.ts). Nothing in the code needs to change when a file is added.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { productCatalog, slugifyTypeName } from '../src/data/productCatalog.ts';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const extensions = ['jpg', 'jpeg', 'png', 'webp', 'avif'];
const shouldWrite = process.argv.includes('--write');

const stylePrompt =
  'studio product photograph, 3/4 angle, soft diffused side light, subtle natural shadow, warm off-white seamless background (#f4f2ee), ' +
  'realistic paper and material texture, sharp focus, no text, no logos, no lorem ipsum, 4:3 landscape, 2000px wide';

const hasImage = (slug, baseName) =>
  extensions.some((extension) => existsSync(path.join(projectRoot, 'public', 'images', 'products', slug, `${baseName}.${extension}`)));

const lines = [
  '# Product image guide',
  '',
  'Generated by `node scripts/image-manifest.mjs --write`. Save each image as the exact file name below, inside',
  '`public/images/products/<product-slug>/` (jpg, jpeg, png, webp or avif). No code change needed.',
  '',
  '**Style for every image:** ' + stylePrompt + '.',
  '',
  '**Do not use:** mockups with text baked in (e.g. "BROCHURE TEMPLATE", "LOREM IPSUM"), other brands\' logos, watermarks.',
  '',
];

let missingCount = 0;
let totalCount = 0;

for (const product of productCatalog) {
  lines.push(`## ${product.name} — \`${product.slug}\`${product.needsConfirmation ? '  _(types need client confirmation)_' : ''}`, '');
  lines.push('| Status | File | Prompt |', '| --- | --- | --- |');

  const coverPresent = hasImage(product.slug, 'cover');
  totalCount += 1;
  if (!coverPresent) missingCount += 1;
  lines.push(
    `| ${coverPresent ? '✅' : '❌'} | \`${product.slug}/cover.jpg\` | ${product.name} hero shot — a small set of 2–3 ${product.name.toLowerCase()} samples arranged together; ${stylePrompt} |`,
  );

  for (const type of product.types) {
    const baseName = slugifyTypeName(type.name);
    const present = hasImage(product.slug, baseName);
    totalCount += 1;
    if (!present) missingCount += 1;
    lines.push(
      `| ${present ? '✅' : '❌'} | \`${product.slug}/${baseName}.jpg\` | ${type.name} (${product.name.toLowerCase()}): ${type.line} ${stylePrompt} |`,
    );
  }
  lines.push('');
}

console.log(`${totalCount - missingCount} of ${totalCount} product images present — ${missingCount} still missing.`);

if (shouldWrite) {
  const outputDirectory = path.join(projectRoot, 'docs');
  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(path.join(outputDirectory, 'product-images.md'), lines.join('\n'));
  console.log('Wrote docs/product-images.md');
}
